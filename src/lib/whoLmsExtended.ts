/** Combina tablas IMC 0–60 y 5–17 en una sola por sexo */
export function getBmiForAgeTable(sex: 'M' | 'F'): LmsTable {
  return { ...BMI_FOR_AGE_0_60[sex], ...BMI_FOR_AGE_5_17[sex] };
}

/** Combina tablas talla 0–60 (WHO_LMS) con 5–17 */
export function mergeHeightForAgeTable(
  base0to5: LmsTable,
  sex: 'M' | 'F'
): LmsTable {
  return { ...base0to5, ...HEIGHT_FOR_AGE_5_17[sex] };
}
